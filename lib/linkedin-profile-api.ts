import { useState, useMemo, useCallback } from 'react'
import { 
  MultiLocaleString, 
  Locale, 
  LinkedInApiUtils,
  LINKEDIN_LOCALES 
} from './linkedin-api-types'

// Profile API Types based on LinkedIn documentation
export interface LinkedInProfile {
  id: string // Person ID - unique identifier for the user
  firstName: MultiLocaleString
  localizedFirstName: string
  lastName: MultiLocaleString
  localizedLastName: string
  headline?: MultiLocaleString
  localizedHeadline?: string
  vanityName?: string // Used for public profile URL: www.linkedin.com/in/{vanityName}
  profilePicture?: {
    displayImage: string // URN to the profile picture
  }
  geoLocation?: GeoLocation
  location?: LegacyLocation
}

export interface GeoLocation {
  geo: string // URN to geo location
  autoGenerated: boolean // Whether location is auto-generated or user-selected
  'geo~'?: {
    id: number
    defaultLocalizedName: {
      locale: Locale
      value: string
    }
  }
}

export interface LegacyLocation {
  postalCode?: string
  standardizedLocationUrn?: string
  userSelectedGeoPlaceCode?: string
  countryCode?: string
}

// Profile API Permissions
export enum ProfilePermission {
  LITE_PROFILE = 'r_liteprofile', // Name and photo
  BASIC_PROFILE = 'r_basicprofile', // Name, photo, headline, vanity name
  COMPLIANCE = 'r_compliance' // Private permission for compliance monitoring
}

// Profile API Client
export class LinkedInProfileApi {
  private accessToken: string
  private baseUrl: string = 'https://api.linkedin.com/v2'

  constructor(accessToken: string) {
    this.accessToken = accessToken
  }

  /**
   * Retrieve current member's profile
   * @see https://learn.microsoft.com/en-us/linkedin/shared/integrations/people/profile-api#retrieve-current-members-profile
   */
  async getCurrentMemberProfile(projection?: string): Promise<LinkedInProfile> {
    const url = projection 
      ? `${this.baseUrl}/me?projection=${projection}`
      : `${this.baseUrl}/me`

    const response = await this.makeRequest(url)
    return this.transformProfileResponse(response)
  }

  /**
   * Retrieve another member's profile by Person ID
   * @see https://learn.microsoft.com/en-us/linkedin/shared/integrations/people/profile-api#retrieve-other-members-profile
   */
  async getMemberProfile(personId: string, projection?: string): Promise<LinkedInProfile> {
    const url = projection
      ? `${this.baseUrl}/people/(id:${personId})?projection=${projection}`
      : `${this.baseUrl}/people/(id:${personId})`

    const response = await this.makeRequest(url)
    return this.transformProfileResponse(response)
  }

  /**
   * Retrieve multiple member profiles at once
   */
  async getMultipleMemberProfiles(personIds: string[], projection?: string): Promise<LinkedInProfile[]> {
    const idsParam = personIds.map(id => `(id:${id})`).join(',')
    const url = projection
      ? `${this.baseUrl}/people?ids=List(${idsParam})&projection=${projection}`
      : `${this.baseUrl}/people?ids=List(${idsParam})`

    const response = await this.makeRequest(url)
    
    // Handle multiple profiles response
    if (response.results) {
      return Object.values(response.results).map((profile: any) => 
        this.transformProfileResponse(profile)
      )
    }
    
    return [this.transformProfileResponse(response)]
  }

  /**
   * Get profile with geo location decoration
   */
  async getProfileWithGeoLocation(personId?: string): Promise<LinkedInProfile> {
    const projection = '(geoLocation(geo~,autoGenerated))'
    
    if (personId) {
      return this.getMemberProfile(personId, projection)
    } else {
      return this.getCurrentMemberProfile(projection)
    }
  }

  /**
   * Get public profile URL from vanity name
   */
  getPublicProfileUrl(vanityName: string): string {
    return `https://www.linkedin.com/in/${vanityName}`
  }

  /**
   * Extract person ID from profile
   */
  extractPersonId(profile: LinkedInProfile): string {
    return profile.id
  }

  /**
   * Get display name from profile
   */
  getDisplayName(profile: LinkedInProfile, preferredLocale?: string): string {
    const firstName = LinkedInApiUtils.getLocalizedString(profile.firstName, preferredLocale)
    const lastName = LinkedInApiUtils.getLocalizedString(profile.lastName, preferredLocale)
    return `${firstName} ${lastName}`.trim()
  }

  /**
   * Get headline from profile
   */
  getHeadline(profile: LinkedInProfile, preferredLocale?: string): string {
    return LinkedInApiUtils.getLocalizedString(profile.headline, preferredLocale)
  }

  /**
   * Get location display name
   */
  getLocationDisplayName(profile: LinkedInProfile): string {
    // Try new geo location first
    if (profile.geoLocation) {
      if (profile.geoLocation['geo~']?.defaultLocalizedName?.value) {
        return profile.geoLocation['geo~'].defaultLocalizedName.value
      }
    }

    // Fallback to legacy location (would need additional API calls)
    if (profile.location?.postalCode) {
      return profile.location.postalCode
    }

    return 'Location not available'
  }

  /**
   * Check if profile has migrated to Bing Geo taxonomy
   */
  isLocationMigrated(profile: LinkedInProfile): boolean {
    return profile.geoLocation?.autoGenerated === false
  }

  /**
   * Make authenticated request to LinkedIn API
   */
  private async makeRequest(url: string): Promise<any> {
    const response = await fetch(url, {
      headers: {
        'Authorization': `Bearer ${this.accessToken}`,
        'X-RestLi-Protocol-Version': '2.0.0',
        'Content-Type': 'application/json'
      }
    })

    if (!response.ok) {
      throw new Error(`LinkedIn API error: ${response.status} ${response.statusText}`)
    }

    return response.json()
  }

  /**
   * Transform raw API response to typed profile
   */
  private transformProfileResponse(response: any): LinkedInProfile {
    return {
      id: response.id,
      firstName: response.firstName,
      localizedFirstName: response.localizedFirstName,
      lastName: response.lastName,
      localizedLastName: response.localizedLastName,
      headline: response.headline,
      localizedHeadline: response.localizedHeadline,
      vanityName: response.vanityName,
      profilePicture: response.profilePicture,
      geoLocation: response.geoLocation,
      location: response.location
    }
  }
}

// React Hook for LinkedIn Profile API
export function useLinkedInProfile(accessToken?: string) {
  const [profile, setProfile] = useState<LinkedInProfile | null>(null)
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState<Error | null>(null)

  const profileApi = useMemo(() => {
    if (!accessToken) return null
    return new LinkedInProfileApi(accessToken)
  }, [accessToken])

  const fetchCurrentProfile = useCallback(async (projection?: string) => {
    if (!profileApi) return

    setLoading(true)
    setError(null)

    try {
      const profileData = await profileApi.getCurrentMemberProfile(projection)
      setProfile(profileData)
    } catch (err) {
      setError(err instanceof Error ? err : new Error('Failed to fetch profile'))
    } finally {
      setLoading(false)
    }
  }, [profileApi])

  const fetchMemberProfile = useCallback(async (personId: string, projection?: string) => {
    if (!profileApi) return

    setLoading(true)
    setError(null)

    try {
      const profileData = await profileApi.getMemberProfile(personId, projection)
      setProfile(profileData)
    } catch (err) {
      setError(err instanceof Error ? err : new Error('Failed to fetch profile'))
    } finally {
      setLoading(false)
    }
  }, [profileApi])

  const fetchMultipleProfiles = useCallback(async (personIds: string[], projection?: string) => {
    if (!profileApi) return []

    setLoading(true)
    setError(null)

    try {
      const profiles = await profileApi.getMultipleMemberProfiles(personIds, projection)
      return profiles
    } catch (err) {
      setError(err instanceof Error ? err : new Error('Failed to fetch profiles'))
      return []
    } finally {
      setLoading(false)
    }
  }, [profileApi])

  const getDisplayName = useCallback((preferredLocale?: string) => {
    if (!profile) return ''
    return profileApi?.getDisplayName(profile, preferredLocale) || ''
  }, [profile, profileApi])

  const getHeadline = useCallback((preferredLocale?: string) => {
    if (!profile) return ''
    return profileApi?.getHeadline(profile, preferredLocale) || ''
  }, [profile, profileApi])

  const getLocationDisplayName = useCallback(() => {
    if (!profile) return ''
    return profileApi?.getLocationDisplayName(profile) || ''
  }, [profile, profileApi])

  const getPublicProfileUrl = useCallback(() => {
    if (!profile?.vanityName) return ''
    return profileApi?.getPublicProfileUrl(profile.vanityName) || ''
  }, [profile, profileApi])

  return {
    profile,
    loading,
    error,
    fetchCurrentProfile,
    fetchMemberProfile,
    fetchMultipleProfiles,
    getDisplayName,
    getHeadline,
    getLocationDisplayName,
    getPublicProfileUrl,
    isLocationMigrated: profile ? profileApi?.isLocationMigrated(profile) : false
  }
}

// Utility functions for working with LinkedIn profiles
export class LinkedInProfileUtils {
  /**
   * Check if profile has required permissions
   */
  static hasPermission(profile: LinkedInProfile, permission: ProfilePermission): boolean {
    switch (permission) {
      case ProfilePermission.LITE_PROFILE:
        return !!(profile.firstName && profile.lastName)
      case ProfilePermission.BASIC_PROFILE:
        return !!(profile.firstName && profile.lastName && profile.headline)
      case ProfilePermission.COMPLIANCE:
        // This is a private permission, would need special handling
        return false
      default:
        return false
    }
  }

  /**
   * Get profile completeness score
   */
  static getCompletenessScore(profile: LinkedInProfile): number {
    let score = 0
    const maxScore = 100

    // Basic info (40 points)
    if (profile.firstName) score += 10
    if (profile.lastName) score += 10
    if (profile.headline) score += 10
    if (profile.vanityName) score += 10

    // Profile picture (20 points)
    if (profile.profilePicture?.displayImage) score += 20

    // Location (20 points)
    if (profile.geoLocation || profile.location) score += 20

    // Additional fields (20 points)
    // Could add more fields as needed

    return Math.min(score, maxScore)
  }

  /**
   * Format profile for display
   */
  static formatProfileForDisplay(profile: LinkedInProfile, locale: string = 'en_US'): {
    name: string
    headline: string
    location: string
    profileUrl: string
    completenessScore: number
  } {
    const api = new LinkedInProfileApi('') // Empty token for utility functions
    
    return {
      name: api.getDisplayName(profile, locale),
      headline: api.getHeadline(profile, locale),
      location: api.getLocationDisplayName(profile),
      profileUrl: profile.vanityName ? api.getPublicProfileUrl(profile.vanityName) : '',
      completenessScore: this.getCompletenessScore(profile)
    }
  }
}

