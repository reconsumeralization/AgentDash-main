#!/usr/bin/env node

/**
 * 🔄 REPOSITORY CREDITS UPDATE SCRIPT
 * Automatically update OSS attribution across all repositories
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

class RepoCreditsUpdater {
  constructor() {
    this.creditsFiles = [
      'CREDITS.md',
      'OSS_ATTRIBUTION.md',
      'LICENSE_ATTRIBUTION.md',
      'THIRD_PARTY_LICENSES.md'
    ];
    
    this.readmeFiles = [
      'README.md',
      'readme.md',
      'Readme.md'
    ];
    
    this.attributionContent = '';
    this.creditsContent = '';
  }

  // Load attribution content from generated files
  loadAttributionContent() {
    try {
      if (fs.existsSync('OSS_ATTRIBUTION.md')) {
        this.attributionContent = fs.readFileSync('OSS_ATTRIBUTION.md', 'utf8');
      }
      
      if (fs.existsSync('CREDITS.md')) {
        this.creditsContent = fs.readFileSync('CREDITS.md', 'utf8');
      }
      
      console.log('✅ Loaded attribution content');
      return true;
    } catch (error) {
      console.error('❌ Failed to load attribution content:', error.message);
      return false;
    }
  }

  // Find all git repositories in the current directory and subdirectories
  findRepositories() {
    const repositories = [];
    
    try {
      // Check current directory
      if (this.isGitRepository('.')) {
        repositories.push({
          path: '.',
          name: path.basename(process.cwd()),
          isCurrent: true
        });
      }
      
      // Find subdirectories that are git repositories
      const subdirs = fs.readdirSync('.', { withFileTypes: true })
        .filter(dirent => dirent.isDirectory())
        .map(dirent => dirent.name);
      
      subdirs.forEach(dir => {
        if (this.isGitRepository(dir)) {
          repositories.push({
            path: dir,
            name: dir,
            isCurrent: false
          });
        }
      });
      
      // Also check parent directories for other repositories
      const parentDirs = ['..', '../..', '../../..'];
      parentDirs.forEach(parentDir => {
        try {
          if (this.isGitRepository(parentDir)) {
            const parentName = path.basename(path.resolve(parentDir));
            repositories.push({
              path: parentDir,
              name: parentName,
              isCurrent: false
            });
          }
        } catch (error) {
          // Skip directories we can't access
        }
      });
      
      console.log(`📁 Found ${repositories.length} git repositories`);
      return repositories;
    } catch (error) {
      console.error('❌ Error finding repositories:', error.message);
      return [];
    }
  }

  // Check if a directory is a git repository
  isGitRepository(dirPath) {
    try {
      const gitPath = path.join(dirPath, '.git');
      return fs.existsSync(gitPath) && fs.statSync(gitPath).isDirectory();
    } catch {
      return false;
    }
  }

  // Update credits file in a repository
  updateCreditsFile(repoPath) {
    const creditsPath = path.join(repoPath, 'CREDITS.md');
    
    try {
      // Check if credits file already exists
      if (fs.existsSync(creditsPath)) {
        const existingContent = fs.readFileSync(creditsPath, 'utf8');
        
        // Check if it's already up to date (contains our signature)
        if (existingContent.includes('<!-- OSS-AUDIT-GENERATED -->')) {
          console.log(`  ⏭️  CREDITS.md already up to date in ${repoPath}`);
          return true;
        }
        
        // Backup existing file
        const backupPath = `${creditsPath}.backup.${Date.now()}`;
        fs.writeFileSync(backupPath, existingContent);
        console.log(`  💾 Backed up existing CREDITS.md to ${backupPath}`);
      }
      
      // Write new credits file
      const content = `${this.creditsContent}

<!-- OSS-AUDIT-GENERATED -->
<!-- Last updated: ${new Date().toISOString()} -->
<!-- Generated by: OSS Audit Script -->
`;
      
      fs.writeFileSync(creditsPath, content);
      console.log(`  ✅ Updated CREDITS.md in ${repoPath}`);
      return true;
    } catch (error) {
      console.error(`  ❌ Failed to update CREDITS.md in ${repoPath}:`, error.message);
      return false;
    }
  }

  // Update README with credits section
  updateReadmeCredits(repoPath) {
    const readmePath = this.findReadmeFile(repoPath);
    
    if (!readmePath) {
      console.log(`  ⚠️  No README found in ${repoPath}`);
      return false;
    }
    
    try {
      const existingContent = fs.readFileSync(readmePath, 'utf8');
      
      // Check if credits section already exists
      if (existingContent.includes('## Credits') || existingContent.includes('## Open Source')) {
        console.log(`  ⏭️  README already has credits section in ${repoPath}`);
        return true;
      }
      
      // Add credits section to README
      const creditsSection = `

## Credits

This project uses open source software. See [CREDITS.md](./CREDITS.md) for a complete list of dependencies and their licenses.

<!-- OSS-AUDIT-GENERATED -->
`;
      
      const updatedContent = existingContent + creditsSection;
      fs.writeFileSync(readmePath, updatedContent);
      console.log(`  ✅ Added credits section to README in ${repoPath}`);
      return true;
    } catch (error) {
      console.error(`  ❌ Failed to update README in ${repoPath}:`, error.message);
      return false;
    }
  }

  // Find README file in repository
  findReadmeFile(repoPath) {
    for (const readmeFile of this.readmeFiles) {
      const readmePath = path.join(repoPath, readmeFile);
      if (fs.existsSync(readmePath)) {
        return readmePath;
      }
    }
    return null;
  }

  // Create comprehensive attribution file
  createAttributionFile(repoPath) {
    const attributionPath = path.join(repoPath, 'OSS_ATTRIBUTION.md');
    
    try {
      if (fs.existsSync(attributionPath)) {
        console.log(`  ⏭️  OSS_ATTRIBUTION.md already exists in ${repoPath}`);
        return true;
      }
      
      const content = `${this.attributionContent}

<!-- OSS-AUDIT-GENERATED -->
<!-- Last updated: ${new Date().toISOString()} -->
<!-- Generated by: OSS Audit Script -->
`;
      
      fs.writeFileSync(attributionPath, content);
      console.log(`  ✅ Created OSS_ATTRIBUTION.md in ${repoPath}`);
      return true;
    } catch (error) {
      console.error(`  ❌ Failed to create OSS_ATTRIBUTION.md in ${repoPath}:`, error.message);
      return false;
    }
  }

  // Update package.json with credits information
  updatePackageJson(repoPath) {
    const packageJsonPath = path.join(repoPath, 'package.json');
    
    try {
      if (!fs.existsSync(packageJsonPath)) {
        console.log(`  ⚠️  No package.json found in ${repoPath}`);
        return false;
      }
      
      const packageJson = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'));
      
      // Add credits information to package.json
      if (!packageJson.credits) {
        packageJson.credits = {
          description: 'This project uses open source software',
          attribution: 'See CREDITS.md for complete attribution',
          generated: new Date().toISOString()
        };
        
        fs.writeFileSync(packageJsonPath, JSON.stringify(packageJson, null, 2));
        console.log(`  ✅ Updated package.json with credits info in ${repoPath}`);
        return true;
      } else {
        console.log(`  ⏭️  package.json already has credits info in ${repoPath}`);
        return true;
      }
    } catch (error) {
      console.error(`  ❌ Failed to update package.json in ${repoPath}:`, error.message);
      return false;
    }
  }

  // Update a single repository
  async updateRepository(repo) {
    console.log(`\n📁 Updating repository: ${repo.name} (${repo.path})`);
    
    const results = {
      repository: repo.name,
      path: repo.path,
      updates: {
        credits: false,
        readme: false,
        attribution: false,
        packageJson: false
      }
    };
    
    // Update CREDITS.md
    results.updates.credits = this.updateCreditsFile(repo.path);
    
    // Update README with credits section
    results.updates.readme = this.updateReadmeCredits(repo.path);
    
    // Create OSS_ATTRIBUTION.md
    results.updates.attribution = this.createAttributionFile(repo.path);
    
    // Update package.json
    results.updates.packageJson = this.updatePackageJson(repo.path);
    
    return results;
  }

  // Update all repositories
  async updateAllRepositories() {
    console.log('🔄 Starting repository credits update...\n');
    
    // Load attribution content
    if (!this.loadAttributionContent()) {
      console.error('❌ Cannot proceed without attribution content');
      return;
    }
    
    // Find all repositories
    const repositories = this.findRepositories();
    
    if (repositories.length === 0) {
      console.log('⚠️  No git repositories found');
      return;
    }
    
    const results = [];
    
    // Update each repository
    for (const repo of repositories) {
      const result = await this.updateRepository(repo);
      results.push(result);
    }
    
    // Generate summary report
    this.generateSummaryReport(results);
  }

  // Generate summary report
  generateSummaryReport(results) {
    const report = {
      timestamp: new Date().toISOString(),
      totalRepositories: results.length,
      successfulUpdates: 0,
      failedUpdates: 0,
      details: results
    };
    
    results.forEach(result => {
      const successCount = Object.values(result.updates).filter(Boolean).length;
      if (successCount > 0) {
        report.successfulUpdates++;
      } else {
        report.failedUpdates++;
      }
    });
    
    // Save report
    fs.writeFileSync('repo-update-report.json', JSON.stringify(report, null, 2));
    
    // Print summary
    console.log('\n📊 UPDATE SUMMARY');
    console.log('=================');
    console.log(`Total repositories: ${report.totalRepositories}`);
    console.log(`Successful updates: ${report.successfulUpdates}`);
    console.log(`Failed updates: ${report.failedUpdates}`);
    
    console.log('\n📋 DETAILED RESULTS:');
    results.forEach(result => {
      console.log(`\n${result.repository}:`);
      console.log(`  CREDITS.md: ${result.updates.credits ? '✅' : '❌'}`);
      console.log(`  README: ${result.updates.readme ? '✅' : '❌'}`);
      console.log(`  OSS_ATTRIBUTION.md: ${result.updates.attribution ? '✅' : '❌'}`);
      console.log(`  package.json: ${result.updates.packageJson ? '✅' : '❌'}`);
    });
    
    console.log('\n📄 Full report saved to: repo-update-report.json');
  }
}

// Run update if called directly
if (require.main === module) {
  const updater = new RepoCreditsUpdater();
  updater.updateAllRepositories().catch(console.error);
}

module.exports = RepoCreditsUpdater;
