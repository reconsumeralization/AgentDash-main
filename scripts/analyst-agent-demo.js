function log(message, type = 'info') {
  const timestamp = new Date().toISOString()
  const colors = {
    info: '\x1b[36m', // Cyan
    success: '\x1b[32m', // Green
    error: '\x1b[31m', // Red
    warning: '\x1b[33m', // Yellow
    fix: '\x1b[35m', // Magenta
    reset: '\x1b[0m'
  }
  console.log(`${colors[type]}[${timestamp}] ${message}${colors.reset}`)
}

