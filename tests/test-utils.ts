// Test helpers
export class TestHelpers {
  /**
   * Wait for a specified amount of time
   */
  static async wait(ms: number): Promise<void> {
    return new Promise(resolve => setTimeout(resolve, ms))
  }

  /**
   * Wait for condition to be true
   */
  static async waitForCondition(
    condition: () => boolean,
    timeout: number = 5000,
    interval: number = 100
  ): Promise<void> {
    const startTime = Date.now()
    
    while (Date.now() - startTime < timeout) {
      if (condition()) {
        return
      }
      await this.wait(interval)
    }
    
    throw new Error(`Condition not met within ${timeout}ms`)
  }

  /**
   * Retry a function until it succeeds or times out
   */
  static async retry<T>(
    fn: () => Promise<T>,
    maxAttempts: number = 3,
    delay: number = 1000
  ): Promise<T> {
    let lastError: Error
    
    for (let attempt = 1; attempt <= maxAttempts; attempt++) {
      try {
        return await fn()
      } catch (error) {
        lastError = error as Error
        if (attempt < maxAttempts) {
          await this.wait(delay)
        }
      }
    }
    
    throw lastError!
  }

  /**
   * Mock fetch with delay
   */
  static mockFetchWithDelay(
    response: any,
    delay: number = 100
  ): any {
    return jest.fn().mockImplementation(() => 
      new Promise(resolve => 
        setTimeout(() => 
          resolve({
            ok: true,
            status: 200,
            json: () => Promise.resolve(response)
          } as Response), 
          delay
        )
      )
    )
  }

  /**
   * Mock fetch with error
   */
  static mockFetchWithError(
    error: Error,
    delay: number = 100
  ): any {
    return jest.fn().mockImplementation(() => 
      new Promise((_, reject) => 
        setTimeout(() => reject(error), delay)
      )
    )
  }

  /**
   * Create mock response
   */
  static createMockResponse(
    data: any,
    status: number = 200,
    statusText: string = 'OK'
  ): Response {
    return {
      ok: status >= 200 && status < 300,
      status,
      statusText,
      json: () => Promise.resolve(data),
      text: () => Promise.resolve(JSON.stringify(data)),
      headers: new Headers(),
      url: 'https://api.example.com',
      redirected: false,
      type: 'basic',
      clone: () => ({} as Response),
      body: null,
      bodyUsed: false,
      arrayBuffer: () => Promise.resolve(new ArrayBuffer(0)),
      blob: () => Promise.resolve(new Blob()),
      formData: () => Promise.resolve(new FormData())
    } as Response
  }
}

// Test assertions
class TestAssertions {
  /**
   * Assert that a value is within a range
   */
  static assertInRange(
    value: number,
    min: number,
    max: number,
    message?: string
  ): void {
    if (value < min || value > max) {
      throw new Error(message || `Value ${value} is not within range [${min}, ${max}]`)
    }
  }

  /**
   * Assert that a string matches a pattern
   */
  static assertMatches(
    value: string,
    pattern: RegExp,
    message?: string
  ): void {
    if (!pattern.test(value)) {
      throw new Error(message || `Value "${value}" does not match pattern ${pattern}`)
    }
  }

  /**
   * Assert that an array contains unique values
   */
  static assertUnique<T>(
    array: T[],
    message?: string
  ): void {
    const unique = new Set(array)
    if (unique.size !== array.length) {
      throw new Error(message || 'Array contains duplicate values')
    }
  }

  /**
   * Assert that a date is within a range
   */
  static assertDateInRange(
    date: Date,
    start: Date,
    end: Date,
    message?: string
  ): void {
    if (date < start || date > end) {
      throw new Error(message || `Date ${date.toISOString()} is not within range [${start.toISOString()}, ${end.toISOString()}]`)
    }
  }
}

