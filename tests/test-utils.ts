// Performance testing utilities
class PerformanceTestUtils {
  /**
   * Measure execution time of a function
   */
  static async measureTime<T>(fn: () => Promise<T>): Promise<{ result: T; duration: number }> {
    const startTime = performance.now()
    const result = await fn()
    const endTime = performance.now()
    const duration = endTime - startTime

    return { result, duration }
  }

  /**
   * Benchmark multiple functions
   */
  static async benchmark<T>(
    functions: Array<{ name: string; fn: () => Promise<T> }>,
    iterations: number = 1
  ): Promise<Array<{ name: string; averageDuration: number; results: T[] }>> {
    const benchmarkResults: Array<{ name: string; averageDuration: number; results: T[] }> = []

    for (const { name, fn } of functions) {
      const durations: number[] = []
      const functionResults: T[] = []

      for (let i = 0; i < iterations; i++) {
        const { result, duration } = await this.measureTime(fn)
        durations.push(duration)
        functionResults.push(result)
      }

      const averageDuration = durations.reduce((sum, duration) => sum + duration, 0) / durations.length

      benchmarkResults.push({
        name,
        averageDuration,
        results: functionResults
      })
    }

    return benchmarkResults
  }

  /**
   * Assert performance threshold
   */
  static assertPerformance(
    duration: number,
    threshold: number,
    message?: string
  ): void {
    if (duration > threshold) {
      throw new Error(message || `Performance threshold exceeded: ${duration}ms > ${threshold}ms`)
    }
  }
}

