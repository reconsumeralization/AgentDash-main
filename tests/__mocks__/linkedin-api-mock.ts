// Test utilities
export class LinkedInApiTestUtils {
  /**
   * Create a mock profile with custom data
   */
  static createMockProfile(overrides: Partial<LinkedInProfile> = {}): LinkedInProfile {
    return {
      ...mockLinkedInProfile,
      ...overrides
    }
  }

  /**
   * Create a mock OAuth response with custom data
   */
  static createMockOAuthResponse(overrides: Partial<typeof mockOAuthResponse> = {}) {
    return {
      ...mockOAuthResponse,
      ...overrides
    }
  }

  /**
   * Create a mock activity record with custom data
   */
  static createMockActivityRecord(overrides: Partial<typeof mockActivityRecord> = {}) {
    return {
      ...mockActivityRecord,
      ...overrides
    }
  }

  /**
   * Setup fetch mock for successful response
   */
  static setupSuccessfulFetch(responseType: keyof typeof mockSuccessfulResponses) {
    mockFetch.mockImplementation(mockSuccessfulResponses[responseType])
  }

  /**
   * Setup fetch mock for error response
   */
  static setupErrorFetch(responseType: keyof typeof mockErrorResponses) {
    mockFetch.mockImplementation(mockErrorResponses[responseType])
  }

  /**
   * Reset fetch mock
   */
  static resetFetchMock() {
    mockFetch.mockReset()
  }

  /**
   * Verify fetch was called with correct parameters
   */
  static verifyFetchCall(
    expectedUrl: string,
    expectedOptions?: RequestInit
  ) {
    expect(mockFetch).toHaveBeenCalledWith(
      expectedUrl,
      expect.objectContaining(expectedOptions || {})
    )
  }

  /**
   * Create mock MultiLocaleString
   */
  static createMockMultiLocaleString(
    enValue: string,
    esValue?: string
  ): MultiLocaleString {
    return {
      localized: {
        'en_US': enValue,
        ...(esValue && { 'es_ES': esValue })
      },
      preferredLocale: {
        country: 'US',
        language: 'en'
      }
    }
  }

  /**
   * Create mock Locale
   */
  static createMockLocale(
    language: string = 'en',
    country: string = 'US'
  ): Locale {
    return {
      language,
      country
    }
  }

  /**
   * Create mock GeoLocation
   */
  static createMockGeoLocation(
    locationName: string = 'San Francisco Bay Area',
    autoGenerated: boolean = false
  ): GeoLocation {
    return {
      geo: 'urn:li:geo:12345',
      autoGenerated,
      'geo~': {
        id: 12345,
        defaultLocalizedName: {
          locale: this.createMockLocale(),
          value: locationName
        }
      }
    }
  }

  /**
   * Create mock LegacyLocation
   */
  static createMockLegacyLocation(
    postalCode: string = '94105',
    countryCode: string = 'us'
  ): LegacyLocation {
    return {
      postalCode,
      standardizedLocationUrn: `urn:li:standardizedLocationKey:(${countryCode},${postalCode})`,
      countryCode
    }
  }
}

